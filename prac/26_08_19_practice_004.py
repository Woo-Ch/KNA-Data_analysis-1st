import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 실습 4. agg 진단표 만들기
# 이름 붙인 agg로 설비 진단표를 만들고 정렬
# 여러 통계를 담은 진단표를 만들고 정렬해 우선순위 파악

# · 설비로 그룹을 나눠 측정수·평균온도·온도편차·평균진동·평균압력을 이름 붙여 집계
report = (
    df.groupby("냉각기상태")
    .agg(
        측정수=("온도", "count"),
        평균온도=("온도", "mean"),
        온도편차=("온도", "std"),
        평균진동=("진동", "mean"),
        평균압력=("압력", "mean"),
    )
    .round(2)
)

print(report)
#        측정수   평균온도  온도편차  평균진동    평균압력
# 냉각기상태
# 고장      40  54.67  3.76  0.69  163.68
# 저하      40  45.46  1.47  0.61  158.49
# 정상      40  35.89  0.36  0.55  160.84

# · 평균압력를 기준으로 내림차순 정렬
print(report.sort_values("평균압력", ascending=False))
# #             측정수   평균온도  온도편차  평균진동    평균압력
# 냉각기상태
# 고장      40  54.67  3.76  0.69  163.68
# 정상      40  35.89  0.36  0.55  160.84
# 저하      40  45.46  1.47  0.61  158.49

# 평균진동의 오름차순 정렬
print(report.sort_values("평균진동", ascending=True))
#        측정수   평균온도  온도편차  평균진동    평균압력
# 냉각기상태
# 정상      40  35.89  0.36  0.55  160.84
# 저하      40  45.46  1.47  0.61  158.49
# 고장      40  54.67  3.76  0.69  163.68

