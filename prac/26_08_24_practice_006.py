# 75%    265.000000  1052.000000  ...   17.000000  363.000000
# max    265.000000  1159.000000  ...   27.000000  384.000000

# .T 사용 시 describe 결과의 axis를 바꿈
# .T 사용한 이유는 아래에서 "격차"라는 새로운 컬럼 추가하기 위함
report2 = (
    df[["실린더압력", "주조압력", "사이클타임", "비스킷두께", "형체력"]].describe().T
)
print(report2)
#   count        mean  ...       75%     max
# 실린더압력  188.0  234.308511  ...   265.000   265.0
# 주조압력   188.0  848.696809  ...  1052.000  1159.0
# 사이클타임  188.0   64.750000  ...    35.925  6170.0
# 비스킷두께  188.0   14.170213  ...    17.000    27.0
# 형체력    188.0  303.106383  ...   363.000   384.0

# · 격차가 큰 순으로 정렬해 이상치 의심 컬럼 확인
# 격차라는 새로운 컬럼 추가해서 계산 결과들을 담기: 새로운 컬럼 이름을 언급하면 추가가 됨
# 그 다음에 격차 결과 순서로 정렬
report2["격차"] = (report2["mean"] - report2["50%"]).abs()

print(report2.sort_values("격차", ascending=False)[["mean", "max", "50%", "격차"]])
