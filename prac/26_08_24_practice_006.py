# · 요약을 컬럼별로 정리하고 평균과 중앙값 격차 계산
report = df[["실린더압력", "주조압력", "사이클타임", "비스킷두께", "형체력"]].describe()
print(report)
# 실린더압력         주조압력  ...       비스킷두께         형체력
# count  188.000000   188.000000  ...  188.000000  188.000000
