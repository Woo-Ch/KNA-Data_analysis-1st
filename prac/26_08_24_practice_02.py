import pandas as pd

df = pd.read_csv("data/16_diecasting.csv")

# 실습2. 조건 필터로 이상치 골라내고 개수·비율
# 경계 밖 값을 조건으로 골라 개수와 비율 확인

# 목표
# 경계 밖 값을 조건으로 골라 개수와 비율 확인

Q1 = df["사이클타임"].quantile(0.25)
Q3 = df["사이클타임"].quantile(0.75)
IQR = Q3 - Q1

lower = Q1 - 1.5 * IQR

upper = Q3 + 1.5 * IQR

# 단계
# · 하한보다 작거나 상한보다 큰 조건을 각각 괄호로 감싸 또는로 연결
mask = (df["사이클타임"] < lower) | (df["사이클타임"] > upper)

# · 조건에 맞는 이상치 행만 골라 확인
print(df[mask][["샷", "사이클타임", "상태"]])
# 샷   사이클타임  상태
# 146  147   125.9   0
# 180  181   652.3   1
# 181  182    93.1   1
# 190  191    91.2   1
# 195  196    76.3   1
# 199  200  6170.0   1

# · sum으로 개수, mean으로 비율 계산
print(mask.sum(), round(mask.mean() * 100, 1))  # 6 3.0

# 예상 결과
# 사이클타임 이상치 6건, 비율 3.0%
