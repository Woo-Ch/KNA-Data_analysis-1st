# 2. 75%와 max 차이가 큰 열을 두 개 이상 찾았는가
# 온도와 전류— max가 멀리 튄 열 찾기
# "CSV에서 직접 해당 row를 찾아서 주석으로 붙여주세요!"

# 오일온도는 75%가 68.1인데 max가 75.0으로 6.9 차이가 남
# 실제 데이터에서 75.0인 행이 2개 존재함
# 2020-03-03 12:36:57 → 오일온도 75.0
# 2020-03-05 08:35:57 → 오일온도 75.0

# 모터전류는 75%가 3.8125이고 max가 6.19로 2.3775 차이가 남
# 실제 데이터에서 max 6.19인 행을 확인함
# 2020-03-03 06:31:23 → 모터전류 6.19
# =================================================================
# 3 모터전류처럼 고른 열과 비교해 차이를 설명
# 모터전류는 75%와 max가 가까움— 온도와의 차이 설명
# 모터전류는 75%와 max의 차이가 비교적 작아 높은 값들이 일정 범위 안에 분포
# 반면 오일온도는 75%가 68.1이고 max가 75.0으로 최댓값까지 추가 상승이 나타난다.

