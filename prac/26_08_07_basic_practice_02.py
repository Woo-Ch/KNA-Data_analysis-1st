# 소숫점 이하의 숫자가 포함된 숫자들을 20개정도 만들어 문자로 배열에 담아주세요 "123.45"
# 그 사이에 엉뚱한 글자들이 포함된 내용도 포함시켜 주세요. "영크크"
# 위 리스트 데이터를 사용해서 문제를 풀어주세요

# 1단계. 여러 측정값(일부는 숫자가 아님)을 반복
# 2딘계. try에서 float로 변환
# 3단계. 변환실패(ValueError)시 continue로 그 줄만 건너뛰기
# 4단계. 정상값만 합계에 더해 출력

num_list = [
    "1.1",
    "1.2",
    "1.3",
    "1.4",
    "1.5",
    "1.6",
    "1.7",
    "1.8",
    "1.9",
    "영크크",
    "2.1",
    "2.2",
    "2.3",
    "2.4",
    "2.5",
    "2.6",
    "2.7",
    "2.8",
    "2.9",
    "3.1",
]

total = 0

for text in num_list:
    try:
        num_change = float(text)
    except ValueError:
        continue

    total += num_change

print(f"정상값의 합계: {total}")

