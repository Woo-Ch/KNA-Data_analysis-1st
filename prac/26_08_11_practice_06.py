# - axis=0 (열별 / 센서별 통계 - 가장 빈번하게 사용!):
#   * 세로 방향(위에서 아래로 행을 따라 내려가며) 집계합니다.
#   * 결과로 0번 열(회전수 전체)의 평균 1829.5와 1번 열(토크 전체)의 평균 35.8이 배열로 반환됩니다.
# - axis=1 (행별 / 시점별 통계):
#   * 가로 방향(왼쪽에서 오른쪽으로 열을 따라 가며) 집계하여 각 시점의 통합 지표를 만듭니다.
