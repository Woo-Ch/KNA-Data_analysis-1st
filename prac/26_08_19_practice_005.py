import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 실습 5. 그룹별 통계량 종합
# 전체·그룹 통계와 진단표를 한 흐름으로
# 전체 통계부터 그룹 진단표까지 한 흐름으로 종합

# · 온도 열의 전체 평균과 표준편차로 기준선 파악
# 온도 -> 냉각효율
print(df["냉각효율"].mean().round(2))  # 31.44
print(df["냉각효율"].std().round(2))  # 11.55

# · 라인별(냉각기상태) 평균(mean)과 중앙값(median)을 함께 구해 치우침 확인
print(df.groupby("냉각기상태")["냉각효율"].agg(["mean", "median"]).round(2))
#         mean  median
# 냉각기상태
# 고장     20.12   19.65
# 저하     27.24   27.40
# 정상     46.96   46.90
# 전체적으로 덜 튀긴하지만 정상이 가장 덜 튄다

# · 설비 진단표를 냉각효율편차 순으로 정렬해 우선 점검 대상 선정
report = (
    df.groupby("밸브상태")
    .agg(
        평균냉각효율=("냉각효율", "mean"),
        냉각효율편차=("냉각효율", "std"),
        평균진동=("진동", "mean"),
    )
    .round(2)
)

print(report)
#       평균냉각효율  냉각효율편차  평균진동
# 밸브상태
# 경미     32.05   11.73  0.62
# 심각     30.85   11.81  0.63
# 정상     31.42   11.49  0.61
# 지연     31.46   12.19  0.62

# 냉각효율편차가 클수록 점검 대상이란 뜻이니까 내림차순으로 정렬해봅시다
print(report.sort_values("냉각효율편차", ascending=False))
#       평균냉각효율  냉각효율편차  평균진동
# 밸브상태
# 지연     31.46   12.19  0.62
# 심각     30.85   11.81  0.63
# 경미     32.05   11.73  0.62
# 정상     31.42   11.49  0.61

# 온도일 때 온도편차 내림차순 정렬
#        평균온도  온도편차  평균진동
# 밸브상태
# 지연    45.86  8.93  0.62
# 심각    46.02  8.40  0.63
# 경미    44.86  8.11  0.62
# 정상    45.11  7.79  0.61

# 지연 > 심각 > 경미 > 정상 순
