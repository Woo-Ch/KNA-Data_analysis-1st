# 실습4. 조건에 맞는 이상 센서값만 불리언 인덱싱으로 선별
import numpy as np

# 회전수와 토크 배열 준비
rpm = np.array([1551, 1408, 1498, 2861, 1425, 1410])
torque = np.array([42.8, 46.3, 49.4, 4.6, 41.9, 65.7])

# 비교 연산으로 회전수가 기준을 넘는 조건 생성 -> 2000 이상
print(rpm[rpm >= 2000])  # [2861]

# 다중 조건으로 회전수 과다 또는(OR |) 토크 과소 위험 시점 필터링
# rpm[0] 데이터와 torque[0] 데이터는 같은 시기의 상황을 다룸
print((rpm > 2000) | (torque < 10))  # [False False False  True False False]

