import pandas as pd

# 실습 1. 상관계수와 상관 행렬 구하기
# 목표
# 두 측정값의 상관계수를 구하고 여러 열의 상관 행렬 읽기

df = pd.read_csv("data/14_hydraulic_qc.csv", encoding="utf-8")

# · corr로 두 지표의 상관계수를 구해 부호와 절댓값 해석
# · 여러 지표 열을 골라 corr로 상관 행렬 생성
print(df[["지표01", "지표02", "지표03", "지표04"]].corr().round(3))
#        지표01   지표02   지표03   지표04
# 지표01  1.000  0.941  0.716 -0.983
# 지표02  0.941  1.000  0.801 -0.940
# 지표03  0.716  0.801  1.000 -0.705
# 지표04 -0.983 -0.940 -0.705  1.000

# · 대각선(항상 1)과 대칭 구조를 확인하고 절댓값 큰 칸 찾기 : -0.983

# 예상 결과
# 지표07-08 상관 -0.969, 네 열 상관 행렬 출력
corr_07_08 = df["지표07"].corr(df["지표08"])

print(round(corr_07_08, 3))  # -0.969
