# 실습5. loc, iloc로 행, 열 동시 선택하기

import pandas as pd

df = pd.read_csv("data/13_diecasting_small.csv")

# loc로 행 범위와 열 이름을 함께 지정
df_sub = df.loc[0:4, ["품질등급", "형체력"]]
print(df_sub)
#  품질등급    형체력
# 0   양품  258.0
# 1   양품  257.0
# 2   주의  253.0
# 3   양품  254.0
# 4   불량  222.0
print(df_sub.shape)  # (5, 2)
# 행은 0~4까지 총 5개임을 확인
# 열은 품질등급, 형체력 2개임을 확인

# 다른 행 범위에서 세 열 선택
df_sub2 = df.loc[10:14, ["형체력", "실린더압력", "주조압력"]]
print(df_sub2)
# 형체력  실린더압력    주조압력
# 10  250.0  215.0  1038.0
# 11  258.0  215.0  1038.0
# 12  354.0  265.0   596.0
# 13  258.0  215.0  1039.0
# 14  258.0  215.0  1041.0
print(df_sub2.shape)  # (5, 3)
# 행은 10~14까지 총 5개임을 확인
# 열은 형체력, 실린더압력, 주조압력 3개임을 확인

# iloc 음수 인덱스로 마지막 행 선택
print(df.iloc[-3:])
# 샷  실린더압력    주조압력  사이클타임  비스킷두께    형체력 품질등급
# 27  28  265.0   595.0   33.8   19.0  355.0   주의
# 28  29  218.0  1055.0   20.7   11.0  255.0   양품
# 29  30  218.0  1054.0   21.4    2.0  253.0   불량
print(len(df.iloc[-3:]))  # 3
# 뒤에서 3개를 가져옴을 확인
