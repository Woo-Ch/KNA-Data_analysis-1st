# 실습 6. 여러 기준 조합 그룹
# 두 기준을 묶어 세분 그룹의 평균과 건수 확인
# 두 기준을 조합해 단일 기준에서 안 보이던 패턴 찾기
import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")
df.info()
# 0   냉각기상태   120 non-null    str
#  1   운전부하    120 non-null    str
#  2   밸브상태    120 non-null    str
#  3   온도      120 non-null    float64
#  4   진동      120 non-null    float64
#  5   압력      120 non-null    float64
#  6   냉각효율    120 non-null    float64
#  7   result  120 non-null    str

# · 라인과 교대 두 기준을 묶어 진동 평균 집계
# 운전부하, 밸브상태 기준순서를 잡아서 각 그룹별 평균 진동
print(df.groupby(["운전부하", "밸브상태"])["진동"].mean().round(3))
# 운전부하  밸브상태
# 고부하   경미      0.608
#       심각      0.632
#       정상      0.582
#       지연      0.613
# 저부하   경미      0.625
#       심각      0.624
#       정상      0.630
#       지연      0.637

# · 같은 두 기준으로 size를 구해 조합별 측정 건수 확인
print(df.groupby(["운전부하", "밸브상태"]).size())
# 운전부하  밸브상태
# 고부하   경미      10
#       심각      11
#       정상      26
#       지연      13
# 저부하   경미      10
#       심각       8
#       정상      35
#       지연       7

print(df[["운전부하", "밸브상태"]].value_counts())
# 운전부하  밸브상태
# 저부하   정상      35
