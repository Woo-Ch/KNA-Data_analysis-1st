# 실습9.Numpy 기초 종합 분석
import numpy as np

# 데이터 불러오기, 구조 확인, 필터링, 통계를 하나의 흐름으로 수행

# np.loadtxt로 회전수와 토크 두 열을 불러오기
rpm = np.loadtxt(
    "data/10_mct_tool.csv", delimiter=",", skiprows=1, usecols=(4, 5), encoding="utf-8"
)
print(rpm)

# shape와 dtype으로 구조 확인
print(rpm.shape, rpm.dtype)  # (40, 2)  float64

# 회전수가 기준 아래로 떨어진 이상 시점을 필터링해 개수와 평균 계산
rpm_data = rpm[:, 0]
print(rpm_data)
# [4603. 4603. 4967. 4603. 4603. 4603. 4603. 4987. 4603. 3632.4603. 4603.
#  4603. 4603. 4603. 4603. 4603. 4603. 4603. 4603.   58. 4603.4603. 1216.
#  4603. 4603. 1217. 4603. 4603. 4603. 4603. 4603. 1241. 4603.4603. 3143.
#  4603. 4967. 4603. 4987.]

anomaly = rpm_data[rpm_data < 1000]
print(anomaly)  # [58.]
print(anomaly.size, round(anomaly.mean(), 1))  # 1  58.0

