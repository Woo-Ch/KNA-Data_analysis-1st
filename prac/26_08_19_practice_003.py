import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 실습 3. agg로 여러 통계 한 번에
# 리스트·이름붙이기 두 방식으로 여러 통계 요약
# 한 번의 agg로 여러 통계를 동시에 구하기

# · 교대로 그룹을 나눠 진동의 평균·표준편차·최댓값을 리스트로 한 번에
# -> 운정부하별 그룹, 진동에 따른 통계들 (평균, 표준편차, 최대값)
# 밸브상태에 따른 온도 평균 편차 최대값
print(df.groupby("밸브상태")["온도"].agg(["mean", "std", "max"]).round(3))
#         mean    std   max
# 밸브상태
# 경미    44.860  8.110  57.1
# 심각    46.021  8.395  57.6
# 정상    45.113  7.790  57.8
# 지연    45.860  8.928  57.5

# · 이름 붙이기 방식으로 설비별 평균온도·평균진동·측정수 요약 ->냉각기상태 에 따른 통계들
print(
    df.groupby("냉각기상태")
    .agg(
        평균온도=("온도", "mean"),
        평균진동=("진동", "mean"),
        측정수=("온도", "count"),  # 몇개의 온도 데이터들이 있는지 세어보기
    )
    .round(3)
)
#          평균온도   평균진동  측정수
# 냉각기상태
# 고장     54.668  0.688   40
# 저하     45.465  0.610   40
# 정상     35.885  0.549   40

# · 두 방식의 결과 표 모양 비교
# agg에 라벨링을 하게 되면 세부 통계항목별로 개별 컬럼들을 따로 지정해 통계낼 수 있음!
