import pandas as pd

df = pd.read_csv("data/16_diecasting.csv", encoding="utf-8")

# 실습7. 여러 컬럼의 가운데 절반 폭 비교
# 세 컬럼의 Q3-Q1을 비교해 안정·의심 컬럼 구분: Q1, Q2, Q3

# 목표
# 세 컬럼의 가운데 절반 폭(Q3-Q1)을 비교

# 단계
# · 세 컬럼의 사분위수를 한 번에 구하기: 실린더압력, 사이클타임, 비스킷두께
three = df[["실린더압력", "사이클타임", "비스킷두께"]].quantile([0.25, 0.5, 0.75])
print(three)
# 실린더압력   사이클타임  비스킷두께
# 0.25  215.75  20.800   11.0
# 0.50  218.00  22.600   13.0
# 0.75  265.00  35.925   17.0

# · 각 컬럼의 75% 값에서 25% 값을 빼 가운데 절반 폭 계산
# loc는 이름으로 찾는 함수
# three에서 0.75가 Index label로 되어있는 row -> three.loc[0.75]
print(three.loc[0.75] - three.loc[0.25])
# 실린더압력    49.250
# 사이클타임    15.125
# 비스킷두께     6.000

# · 폭이 좁은 안정 컬럼과 넓은 의심 컬럼 구분
# 비스킷두께는 가운데 50%의 폭이 6으로 가장 좁아 값이 비교적 모여 있음
# 실린더압력은 가운데 50%의 폭이 49.25로 가장 넓어 값의 퍼짐이 큼
# 사이클타임은 15.125로 두 컬럼의 중간 정도

